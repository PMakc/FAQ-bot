def handle_callback(update):

    callback = update.get("callback", {})

    callback_id = callback.get("callback_id")

    payload = callback.get("payload")

    logging.info(
        "message_callback: callback_id=%s payload=%r",
        callback_id,
        payload
    )

    if not callback_id:
        logging.error(
            "В callback отсутствует callback_id:\n%s",
            update
        )
        return

    if payload == "main":

        answer_callback(
            callback_id,
            main_menu_text(),
            main_menu_keyboard()
        )

        return

    # ----------------------------------------
    # РАЗДЕЛ
    # ----------------------------------------

    if isinstance(payload, str) and payload.startswith("section:"):

        section_id = payload.split(":", 1)[1]

        if section_id not in FAQ:

            answer_callback(
                callback_id,
                "❌ Такой раздел не найден.",
                main_menu_keyboard()
            )

            return

        answer_callback(
            callback_id,
            section_text(section_id),
            section_keyboard(section_id)
        )

        return

    # ----------------------------------------
    # ВОПРОС
    # ----------------------------------------

    if isinstance(payload, str) and payload.startswith("question:"):

        parts = payload.split(":")

        if len(parts) != 3:

            answer_callback(
                callback_id,
                "❌ Некорректная кнопка.",
                main_menu_keyboard()
            )

            return

        section_id = parts[1]
        question_id = parts[2]

        if section_id not in FAQ:

            answer_callback(
                callback_id,
                "❌ Раздел не найден.",
                main_menu_keyboard()
            )

            return

        questions = FAQ[section_id]["questions"]

        if question_id not in questions:

            answer_callback(
                callback_id,
                "❌ Вопрос не найден.",
                section_keyboard(section_id)
            )

            return

        question = questions[question_id]

        answer_callback(
            callback_id,
            question["answer"],
            question_keyboard(section_id)
        )

        return

    # ----------------------------------------
    # НЕИЗВЕСТНЫЙ CALLBACK
    # ----------------------------------------

    answer_callback(
        callback_id,
        "❌ Неизвестная команда.",
        main_menu_keyboard()
    )


