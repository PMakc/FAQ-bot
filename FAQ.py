def load_token():

    if not os.path.exists(TOKEN_FILE):
        raise FileNotFoundError(
            f"Файл {TOKEN_FILE} не найден."
        )

    with open(TOKEN_FILE, "r", encoding="utf-8") as f:
        token = f.read().strip()

    if not token:
        raise ValueError(
            "Файл bot_token.txt пустой."
        )

    return token


