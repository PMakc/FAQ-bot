def callback_button(text, payload):

    return {
        "type": "callback",
        "text": text,
        "payload": payload
    }


def make_keyboard(buttons, columns=2):

    rows = []

    for i in range(0, len(buttons), columns):
        rows.append(
            buttons[i:i + columns]
        )

    return rows


def keyboard_attachment(buttons):

    return {
        "type": "inline_keyboard",
        "payload": {
            "buttons": buttons
        }
    }


